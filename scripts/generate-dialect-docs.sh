#!/usr/bin/env bash
# The reference of the dialects' ops, types, and attributes, generated from
# their TableGen definitions (#610):
#
#   scripts/generate-dialect-docs.sh MLIR_TBLGEN LLVM_INCLUDE_DIR OUT_DIR
#
# writes OUT_DIR/<dialect>.md for md, dyn, md_exec, md_dist, and mdrt with
# `mlir-tblgen -gen-dialect-doc`. The build runs it (the target
# mdir-dialect-docs, into <build>/docs/dialects); docs/dialects/ holds the
# output, checked in, and test/Docs/dialect-docs.test fails when the two
# differ. After a change of a .td file, copy the build's files there:
#
#   cp <build>/docs/dialects/*.md docs/dialects/
set -euo pipefail
tblgen=${1:?usage: $0 MLIR_TBLGEN LLVM_INCLUDE_DIR OUT_DIR}
llvm_include=${2:?usage: $0 MLIR_TBLGEN LLVM_INCLUDE_DIR OUT_DIR}
out=${3:?usage: $0 MLIR_TBLGEN LLVM_INCLUDE_DIR OUT_DIR}
source=$(cd "$(dirname "$0")/.." && pwd)
mkdir -p "$out"
for entry in MD:md:MDOps Dyn:dyn:DynOps MDExec:md_exec:MDExecOps \
             MDDist:md_dist:MDDistOps MDRT:mdrt:MDRTOps; do
  IFS=: read -r directory dialect file <<<"$entry"
  "$tblgen" -gen-dialect-doc -dialect="$dialect" \
    -I "$source/include" -I "$llvm_include" \
    "$source/include/mdir/Dialect/$directory/$file.td" -o "$out/$dialect.md.tmp"
  {
    echo "<!-- Generated by scripts/generate-dialect-docs.sh from"
    echo "     include/mdir/Dialect/$directory/$file.td; do not edit (#610). -->"
    echo
    # GitHub does not render the [TOC] of the MLIR site.
    grep -v "^\[TOC\]$" "$out/$dialect.md.tmp"
  } > "$out/$dialect.md"
  rm -f "$out/$dialect.md.tmp"
done
