def replace_once(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)


def generate(text, spec):
    """The template `text` with its generated part written anew."""
    start = text.index("func.func private " + spec["pass"] + "(")
    stop = text.index("\n}\n", start) + 3
    body = text[start:stop]
    body = replace_once(body, spec["pass"] + "(", spec["images"] + "(")
    body = replace_once(body, SETUP_OLD, SETUP_NEW)
    body = replace_once(body, spec["test_old"], spec["test_new"])
    generated = (BEGIN + "\n" + WITHIN.replace("@NAME", spec["within"]) +
                 spec["doc"] + body + "\n" + spec["dispatch"] + END)
    begin = text.index(BEGIN)
    end = text.index(END, begin) + len(END)
    return text[:begin] + generated + text[end:]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    templates = os.path.join(here, "..", "lib", "Runtime", "Templates")
    target = sys.argv[1] if len(sys.argv) > 1 else templates
    for spec in (HOST, DEVICE):
        with open(os.path.join(templates, spec["file"])) as file:
            text = file.read()
        with open(os.path.join(target, spec["file"]), "w") as file:
            file.write(generate(text, spec))


if __name__ == "__main__":
    main()
