def influence_function(source, target, base=None):
    text = function(source, base)
    text = text.replace('@' + source + '(', '@' + target + '(', 1)
    # The block of F(b) of the dispersion, from |m| to the factor of the
    # virial.
    start = text.index('%dmabs = math.sqrt')
    start = text.rindex('\n', 0, start) + 1
    marker = '%vb = arith.mulf %tt123, %dvd1 : !pme_real\n'
    end = text.index(marker) + len(marker)
    block = text[start:end]
    # tt12 and tt123 are computed inside the block of the dispersion.
    text = text[:start] + INFLUENCE + text[end:]
    # pe, after the scalars of the function.
    anchor = '  %c1 = arith.constant 1 : index\n'
    text = text.replace(anchor, anchor + '''  %pk12 = arith.addi %k1, %k2 : index
  %pk123 = arith.addi %pk12, %k3 : index
  %pc3 = arith.constant 3 : index
  %pe = arith.muli %pk123, %pc3 : index
''', 1)
    return text


def check_names(text):
    """Every value of the influence block is defined in the function that
    it is put into: the names it reads from the dispersion's."""
    for name in ['%msqr', '%t1', '%t2', '%t3', '%rone', '%cc1']:
        assert name in text, name


def tables(triclinic=False):
    """The factors of the edges: m, m², and 1/φ̂₁² along each edge, the
    first times f / (π V) (as tables_dispersion, with the prefactor of the
    Coulomb sum)."""
    suffix = '_triclinic' if triclinic else ''
    text = function('mdrt_gpu_pme_tables_dispersion' + suffix, TRICLINIC if triclinic else None)
    text = text.replace('@mdrt_gpu_pme_tables_dispersion' + suffix + '(', '@mdrt_gpu_pme_prolate_tables' + suffix + '(', 1)
    old = '''  %pi32 = arith.constant 5.568327996831708 : f64
  %beta3 = arith.mulf %beta2, %beta : f64
  %pb3 = arith.mulf %pi32, %beta3 : f64
  %three = arith.constant 3.0 : f64
  %v3 = arith.mulf %three, %volume : f64
  %pd0 = arith.divf %pb3, %v3 : f64
  %pdc = arith.mulf %pd0, %coulomb : f64
  %prefactor = arith.negf %pdc : f64
'''
    assert old in text
    text = text.replace(old, '''  %prefactor = arith.divf %coulomb, %piv : f64
''')
    return text


def tiles():
    """The spreading of the window into tiles of the bins of
    PMEGPU.mlir (D282; tile_kernel of
    generate-pme-gpu-template.py): the lanes 0 .. 3P − 1 of the warp of a
    particle evaluate the window from the fraction of their axis, which
    the tile kernel has read into the memory of the block, as the bricks
    do (warp_weights)."""
    lane = '''          %two_i = arith.constant 2 : index
          %three_i = arith.constant 3 : index
          %one = arith.constant 1 : index
          %points = arith.constant PME_ORDER : index
          %k12t = arith.addi %k1, %k2 : index
          %k123t = arith.addi %k12t, %k3 : index
          %pe = arith.muli %k123t, %three_i : index
          %j = arith.addi %j_l, %c0 : index
          %twor = arith.constant 2.0 : !pme_real
          %oner = arith.constant 1.0 : !pme_real
          %frac2 = arith.mulf %frac, %twor : !pme_real
          %t = arith.subf %frac2, %oner : !pme_real
          %meta_d = arith.addi %pe, %two_i : index
          %dr = memref.load %tables[%meta_d] : memref<?x!pme_real, 1>
          %meta_n = memref.load %tables[%pe] : memref<?x!pme_real, 1>
          %terms_i = arith.fptosi %dr : !pme_real to i32
          %terms = arith.index_cast %terms_i : i32 to index
          %n_i = arith.fptosi %meta_n : !pme_real to i32
          %n_s = arith.index_cast %n_i : i32 to index
          %n_2 = arith.addi %n_s, %n_s : index
          %wb0 = arith.addi %pe, %three_i : index
          %wbase = arith.addi %wb0, %n_2 : index
''' + clenshaw('wv', '%wbase', '%t', 'wvalue0') + '''          %wvalue = arith.select %active, %wvalue0, %zero_r : !pme_real
          %first_axis = arith.cmpi eq, %axis_l, %c0 : index
          %qv = arith.mulf %wvalue, %qk : !pme_real
          %weight = arith.select %first_axis, %qv, %wvalue : !pme_real
'''
    text = ''
    for edge in GAUSSIAN.TILE_EDGES:
        text += GAUSSIAN.tile_kernel(
            edge, 'mdrt_gpu_pme_prolate_spread_tiles',
            '%q: memref<?x!pme_chg, 1>, %places: memref<?x!pme_real, 1>, %tables: memref<?x!pme_real, 1>,',
            lane,
            'Adds the charges of the binned particles to `real` through tiles of\n'
            '// the memory of the block, with the window (D282, D266).')
    return text


def main():
    out = HEADER + coefficients() + places(False) + places(True) + spread(fixed=False) + spread(fixed=True)
    out += gather(potential=False) + gather(potential=True)
    out += gather(potential=False, triclinic=True) + gather(potential=True, triclinic=True)
    out += tables() + tables(triclinic=True)
    for suffix, base in (('', None), ('_triclinic', TRICLINIC)):
        convolve = influence_function('mdrt_gpu_pme_convolve_dispersion' + suffix,
                                      'mdrt_gpu_pme_prolate_convolve' + suffix, base)
        scale = influence_function('mdrt_gpu_pme_scale_dispersion' + suffix,
                                   'mdrt_gpu_pme_prolate_scale' + suffix, base)
        check_names(convolve)
        check_names(scale)
        out += '// The product with the influence function of the prolate kernel, with the\n'
        out += '// energy and the virial (convolve_dispersion with χ̂ in place of F).\n' + convolve + '\n'
        out += '// The product alone (scale_dispersion with χ̂ in place of F).\n' + scale + '\n'
    # The kernels of a list of the particles (D262), after the others, so
    # that those of a module without a list are those of before; the
    # compiler adds them where a sum has a list.
    out += spread(fixed=False, listed=True) + spread(fixed=True, listed=True)
    out += gather(potential=False, listed=True) + gather(potential=False, triclinic=True, listed=True)
    # The spreading into tiles (D282), after them for the same
    # reason.
    out += tiles()
    out = out.replace('@mdrt_gpu_pme_blocks(', '@mdrt_gpu_pme_prolate_blocks(')
    out = out.replace('@mdrt_gpu_pme_blocks_triclinic(', '@mdrt_gpu_pme_prolate_blocks(')
    sys.stdout.write(out)


main()
