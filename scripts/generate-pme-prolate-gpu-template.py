#!/usr/bin/env python3
"""Writes lib/Runtime/Templates/PMEGPUProlate.mlir, the kernels of the
reciprocal sum of particle mesh Ewald with the prolate kernel on a device
(D266): Ewald summation with prolates [Liang2026].

    python3 scripts/generate-pme-prolate-gpu-template.py > lib/Runtime/Templates/PMEGPUProlate.mlir

The influence function and its tables are made from those of the sum of
the dispersion in PMEGPU.mlir (convolve_dispersion, scale_dispersion,
tables_dispersion), whose function of |m| this replaces; the copy of the
bricks into the grid is that of spread_bricks (D108). The rest is written
here. The measurement P0 of #337 set the form of the window: each weight
and slope is evaluated once a particle, by 3P lanes of a warp, from
coefficients in the type of the grid laid out term by term so that the
lanes of a term read adjacent words; the other lanes take them by
shuffles."""

